"""Unit and integration tests for verify_door_sync script."""

from __future__ import annotations

import argparse

import pytest

from scripts.verify_door_sync import build_parser, run_verification


def test_build_parser_defaults() -> None:
    """Test CLI argument parser configurations and defaults."""
    parser = build_parser()
    args = parser.parse_args(["--dry-run", "--non-interactive"])

    assert args.dry_run is True
    assert args.non_interactive is True
    assert args.booking_id == "manual-verify-01"
    assert args.pin is None
    assert args.guest_slot_min == 3
    assert args.guest_slot_max == 9
    assert args.duration_hours == 2.0
    assert args.lead_time == 60
    assert args.grace_period == 15
    assert args.skip_cleanup is False


