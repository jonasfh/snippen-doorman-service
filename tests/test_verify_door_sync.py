@pytest.mark.asyncio
async def test_run_verification_interactive_status_query(monkeypatch) -> None:
    """Test interactive prompt handling 'r' status command before confirming [ENTER]."""
    args = argparse.Namespace(
        dry_run=True,
        non_interactive=False,
        address=None,
        key=None,
        key_slot=1,
        api_url=None,
        api_token=None,
        booking_id="test-interactive-01",
        pin="112233",
        duration_hours=2.0,
        guest_slot_min=3,
        guest_slot_max=9,
        lead_time=60,
        grace_period=15,
        skip_cleanup=False,
        timeout=10.0,
    )

    # First user input simulates 'r' (status), second user input simulates '' (ENTER)
    inputs = iter(["r", ""])
    monkeypatch.setattr("builtins.input", lambda _: next(inputs))

    exit_code = await run_verification(args)
    assert exit_code == 0
